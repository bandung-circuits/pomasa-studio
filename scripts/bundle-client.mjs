#!/usr/bin/env node
/**
 * Bundle src/client modules into lib/client.js (__ModuleLoader__ format).
 * React is provided by the host (require("react")) — per DSH slot spec we
 * cannot `import` anything. markdown-it is NOT importable in the browser
 * either, so scripts/md-api.mjs is esbuild-bundled to a self-contained
 * __psMd IIFE and inlined at the top of the factory (the same injection
 * Auctor uses for __auctorMd); the rest remains plain concatenation.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const CLIENT_DIR = path.join(ROOT, 'src/client')

function read(name) {
  return fs.readFileSync(path.join(CLIENT_DIR, name), 'utf8')
}

function stripModuleSyntax(src) {
  return src
    .replace(/^export const inject = .*$/m, '')
    .replace(/^export function apply/m, 'function apply')
    .replace(/^export function /gm, 'function ')
    .replace(/^export const /gm, 'const ')
    .replace(/^export \{[^}]+\}\s*;?\s*$/gm, '')
    .replace(/^import .+ from .+;?\s*$/gm, '')
}

// styles.js keeps its template-literal shape: turn `export const CSS = `...`` into `const CSS = `...``
const styles = read('styles.js').replace('export const CSS = ', 'const CSS = ')
const api = stripModuleSyntax(read('api.js'))
const md = stripModuleSyntax(read('md.js'))
const i18n = stripModuleSyntax(read('i18n.js'))
const components = stripModuleSyntax(read('components.js'))
const meme = stripModuleSyntax(read('meme.js'))
const pages = stripModuleSyntax(read('pages.js'))
const main = stripModuleSyntax(read('main.js'))

// markdown-it 内联包：打成独立 IIFE 注入为 __psMd 全局，客户端渲染器只调用不二次解析。
const mdResult = await build({
  entryPoints: [path.join(ROOT, 'scripts/md-api.mjs')],
  bundle: true,
  format: 'iife',
  globalName: '__psMd',
  write: false,
  platform: 'browser',
  target: 'es2018',
  minify: true,
  logLevel: 'error',
})
const mdText = mdResult.outputFiles[0].text // ends with `var __psMd = ...;\n`

const bundle = `/**
 * pomasa-studio browser bundle — generated by scripts/bundle-client.mjs
 */
window.__ModuleLoader__.load({
  id: "pomasa-studio",
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
    var React = require("react");
    var h = React.createElement;

${mdText}

${styles}

${api}

${md}

${i18n}

${components}

${meme}

${pages}

${main}

    exports.apply = apply;
    exports.inject = ["slots", "workspaces", "sessions"];
    return module.exports;
  }
});
`

fs.writeFileSync(path.join(ROOT, 'lib/client.js'), bundle)
console.log('Wrote lib/client.js (' + bundle.length + ' bytes, markdown-it inlined)')