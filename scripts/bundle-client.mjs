const ASSETS_DIR = path.join(ROOT, 'assets')

const ICON_NAMES = ['info', 'back', 'settings', 'blueprint', 'chat', 'output', 'pomasa', 'send', 'add', 'zoom', 'expand', 'switch', 'close']

