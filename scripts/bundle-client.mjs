#!/usr/bin/env node
/**
 * Bundle src/client (real ESM) into lib/client.js in the dsh __ModuleLoader__
 * format. react / react-dom stay external — the factory's scoped require
 * resolves them from the host runtime, same as before.
 */
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import * as esbuild from 'esbuild'

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)))

export async function buildClient({ outfile = path.join(ROOT, 'lib/client.js'), entry = path.join(ROOT, 'src/client/main.js') } = {}) {
  await esbuild.build({
    entryPoints: [entry],
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    external: ['react', 'react-dom'],
    inject: [path.join(ROOT, 'scripts/react-shim.js')],
    loader: { '.svg': 'text' },
    banner: {
      js: [
        '/**',
        ' * pomasa-studio browser bundle — generated by scripts/bundle-client.mjs (esbuild)',
        ' */',
        'window.__ModuleLoader__.load({',
        '  id: "pomasa-studio",',
        '  factory: (require) => {',
        '    var module = { exports: {} };',
        '    var exports = module.exports;',
      ].join('\n'),
    },
    footer: { js: '    return module.exports;\n  }\n});' },
    outfile,
  })
  return outfile
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const out = await buildClient()
  const { size } = await import('node:fs').then((m) => m.statSync(out))
  console.log('Wrote lib/client.js (' + size + ' bytes)')
}
