function read(name) {
  return fs.readFileSync(path.join(CLIENT_DIR, name), 'utf8')
}

function readIconsModule() {
  const svgs = {}
  for (const name of ICON_NAMES) {
    svgs[name] = fs.readFileSync(path.join(ASSETS_DIR, name + '.svg'), 'utf8')
  }
  return 'const ICON_SVGS = ' + JSON.stringify(svgs) + ';\n\n' + stripModuleSyntax(read('icons/icons.js'))
}

function stripModuleSyntax(src) {
  return src
    .replace(/^export const inject = .*$/m, '')
    .replace(/^export function apply/m, 'function apply')
    .replace(/^export async function /gm, 'async function ')
    .replace(/^export function /gm, 'function ')
    .replace(/^export const /gm, 'const ')
    .replace(/^export let /gm, 'let ')
    .replace(/^export var /gm, 'var ')
    .replace(/^export class /gm, 'class ')
    .replace(/^export \{[^}]+\}\s*;?\s*$/gm, '')
    .replace(/^import .+ from .+;?\s*$/gm, '')
}

const styles = read('styles.js').replace('export const CSS = ', 'const CSS = ')
const parts = CLIENT_BUNDLE_FILES.map((name) => {
  if (name === 'icons/icons.js') return readIconsModule()
  return stripModuleSyntax(read(name))
})
const bundle = `/**
 * pomasa-studio browser bundle — generated by scripts/bundle-client.mjs
 */
window.__ModuleLoader__.load({
  id: "pomasa-studio",
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
    var React = require("react");
    var ReactDOM = require("react-dom");
    var h = React.createElement;

${styles}

${parts.join('\n\n')}

    exports.apply = apply;
    exports.inject = ["slots", "workspaces", "sessions"];
    return module.exports;
  }
});
`

fs.writeFileSync(path.join(ROOT, 'lib/client.js'), bundle)
console.log('Wrote lib/client.js (' + bundle.length + ' bytes)')
